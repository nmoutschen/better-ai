"""architect-better's own verbs: `review`, `specs`, `register` and `render`, and the guard that keeps `reviews.jsonl`
for `review`.

- `review <unit> --perspectives <id>...` records the fingerprints of the diagram's parts, the requirements and the
  design document's sections a review covered;
- `specs <unit>` prints `specs.md`, made from `spec.jsonl` and marked as generated, on stdout;
- `register <unit>` writes the register of box kinds into the unit;
- `render <unit>` writes the page as one static file, and the Before and After SVGs, into the unit's `render/` folder.
"""

from __future__ import annotations

import argparse
import json

from .. import cli, page, paths, records, schema
from ..paths import Unit
from . import SKILL, diagram, model

# Written at the top of a specs.md made from spec.jsonl, so nobody edits the copy by hand.
GENERATED = "<!-- Generated by architect-better from spec.jsonl. Do not edit it by hand: change spec.jsonl and generate it again. -->"
RENDER_FOLDER = "render"


def _unit_argument(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("unit", help="the change folder, such as .architect/my-change")


def error_lines(errors: list[dict]) -> list[str]:
    return [f"{e['file']}:{e['line']}: {e['field']}: {e['message']}" for e in errors]


# ---------------------------------------------------------------- review


@records.add_guard(SKILL.name, "review")
def _no_add_review(ctx: records.AddContext) -> None:
    raise paths.refusal(
        ctx.unit.label,
        "reviews.jsonl is written by review, which records the fingerprints of the design's parts",
        f"run review {ctx.unit.label} --perspectives <id>...",
    )


def _review_arguments(parser: argparse.ArgumentParser) -> None:
    _unit_argument(parser)
    parser.add_argument(
        "--perspectives", nargs="+", required=True, metavar="ID", help="the ids of the perspectives that were reviewed"
    )


@cli.verb(
    "review",
    help="record the reviewed diagram fingerprints for the perspectives that ran",
    arguments=_review_arguments,
    skills=(SKILL.name,),
)
def review(args: argparse.Namespace, run: cli.Run) -> int:
    unit = paths.resolve_unit(args.unit, run.skill)
    data = model.read_folder(unit)
    if data["errors"]:
        raise paths.refusal(
            unit.label,
            "the folder is not valid",
            "fix these, then run review again:\n" + "\n".join(error_lines(data["errors"])),
        )
    applicable = {p["id"] for p in data["perspectives"] if p["applies"]}
    for ident in args.perspectives:
        if ident not in applicable:
            raise paths.refusal(
                unit.label,
                f"{ident!r} is not the id of a perspective that applies",
                "use an id from perspectives.jsonl",
            )
    previous = data["reviews"][-1] if data["reviews"] else None
    record = {
        "type": "review",
        "at": run.now().strftime(schema.TIME),
        "by": "architect",
        "perspectives": list(dict.fromkeys(args.perspectives)),
        "changed": model.changed_parts(data["hashes"], previous),
        "hashes": data["hashes"],
        "labels": {key: data["parts"][key]["label"] for key in data["hashes"]},
        "texts": data["texts"],
    }
    problems = schema.check_record(record, ["reviews.schema.json"])
    if problems:
        raise paths.refusal(unit.label, "the review is not valid: " + "; ".join(f"{f}: {m}" for f, m in problems))
    try:
        existing = paths.read_bytes(unit, "reviews.jsonl")
    except FileNotFoundError:
        existing = b""
    separator = "\n" if existing and not existing.endswith(b"\n") else ""
    paths.append_line(unit, "reviews.jsonl", (separator + json.dumps(record)).encode("ascii"))
    run.out(f"Recorded the review of {', '.join(record['perspectives'])} in {unit.label}/reviews.jsonl.")
    return 0


# ---------------------------------------------------------------- specs


def cell(value) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def source_words(source) -> str:
    """A spec source in words, for the table of specs.md."""
    if not isinstance(source, dict):
        return ""
    kind = source.get("type")
    if kind == "design":
        return f"design: {source.get('section', '')}"
    if kind == "request":
        return f'request: "{source.get("sentence", "")}"'
    return f"{kind} {source.get(kind, '')}"


def specs_md(records_: list[dict], meta: dict) -> str:
    """The spec for a repo with no spec format or tool, written from spec.jsonl and marked as generated."""
    out = [GENERATED, "", f"# Spec: {meta.get('title', '')}", ""]
    if meta.get("summary"):
        out += [meta["summary"], ""]
    out += ["| ID | Requirement | Source | Checked by |", "|---|---|---|---|"]
    for record in records_:
        if record.get("type") == "spec":
            statement, checked = cell(record.get("statement", "")), cell(record.get("checked_by", ""))
            out.append(
                f"| {record.get('id', '')} | {statement} | {cell(source_words(record.get('source')))} | {checked} |"
            )
    gaps = [r for r in records_ if r.get("type") == "gap"]
    if gaps:
        out += ["", "## Gaps", ""]
        for gap in gaps:
            if gap.get("status") == "assumed":
                how = f"assumed: {gap.get('choice')}"
            else:
                how = f"{gap.get('status')} ({gap.get('decision')})"
            out.append(
                f"- {gap.get('id')}: {gap.get('text')} {how}. If wrong, the user would see: {gap.get('if_wrong')}"
            )
    unlinked = [r for r in records_ if r.get("type") == "unlinked"]
    if unlinked:
        out += ["", "## Design items with no requirement", ""]
        out += [f"- {item.get('item')}: {item.get('why')}" for item in unlinked]
    return "\n".join(out) + "\n"


@cli.verb(
    "specs",
    help="print specs.md, made from spec.jsonl and starting with the generated marker",
    arguments=_unit_argument,
    skills=(SKILL.name,),
)
def specs(args: argparse.Namespace, run: cli.Run) -> int:
    unit = paths.resolve_unit(args.unit, run.skill)
    data = model.read_folder(unit)
    mine = [e for e in data["errors"] if e["file"] in ("spec.jsonl", "architect.json")]
    if mine:
        raise paths.refusal(
            unit.label, "spec.jsonl is not valid", "fix these, then run specs again:\n" + "\n".join(error_lines(mine))
        )
    if not any(r.get("type") == "spec" for r in data["spec"]):
        raise paths.refusal(unit.label, "spec.jsonl has no records", "write the spec first")
    run.out(specs_md(data["spec"], data["architect"]).rstrip("\n"))
    return 0


# ---------------------------------------------------------------- register


@cli.verb(
    "register",
    help="write the register of box kinds and their icons into the unit",
    arguments=_unit_argument,
    skills=(SKILL.name,),
)
def register(args: argparse.Namespace, run: cli.Run) -> int:
    unit = paths.resolve_unit(args.unit, run.skill)
    paths.write_atomic(unit, "register.html", diagram.register().encode("utf-8"))
    run.out(f"Wrote {unit.label}/register.html: open it to see the box kinds.")
    return 0


# ---------------------------------------------------------------- render


def static_page(unit: Unit, run: cli.Run, payload: dict) -> str:
    """The page as one file, with the payload and the conversation, to read, embedded, so it opens without a server."""
    spec = page.spec_of(run.skill)
    events = page.Conversation(unit, spec, page.load_docs(run.skill)).events()
    return page.static_page(spec, {**payload, "events": [e for e in events if e], "static": True})


@cli.verb(
    "render",
    help="write the page as one file, and the Before and After SVGs, into the unit's render folder",
    arguments=_unit_argument,
    skills=(SKILL.name,),
)
def render(args: argparse.Namespace, run: cli.Run) -> int:
    unit = paths.resolve_unit(args.unit, run.skill)
    payload = model.load(unit)
    broken = [e for e in payload["errors"] if e["file"] == "design.json" or e["file"] == "(unit)"]
    if broken:
        raise paths.refusal(
            unit.label,
            "design.json cannot be drawn",
            "fix these, then run render again:\n" + "\n".join(error_lines(broken)),
        )
    design = model.read_folder(unit)["design"]
    files = {name: svg + "\n" for name, svg in diagram.drawings(design).items()}
    paths.make_folder(unit, RENDER_FOLDER)
    for name, svg in files.items():
        paths.write_atomic(unit, f"{RENDER_FOLDER}/{name}", svg.encode("utf-8"))
    paths.write_atomic(
        unit,
        f"{RENDER_FOLDER}/index.html",
        page.with_old_note(unit, static_page(unit, run, payload)).encode("utf-8"),
    )
    if payload["errors"]:
        run.err(f"warning: {len(payload['errors'])} records are not valid: run check {unit.label}")
    run.out(f"Wrote {unit.label}/{RENDER_FOLDER}/index.html and {len(files)} SVGs.")
    return 0
