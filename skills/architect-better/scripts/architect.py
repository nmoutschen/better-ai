#!/usr/bin/env python3
"""Serve the live architecture design and carry review requests to the architect.

CHANGE is the change folder, in the formats of schemas/: architect.json (the request, the title, the summary, the scope
and the accepted sections), design.json (the containers and flows), requirements.jsonl, perspectives.jsonl,
findings.jsonl, reviews.jsonl, decisions.jsonl and spec.jsonl. The change-folder format and review handoff are
documented in example/README.md.

Every record is checked against its schema on its own, through schema.py. The page shows each valid record; the invalid
ones, with where they are, which field and why, are listed in an errors band, and `check` prints the same list: one bad
record never hides the others, and a bad file never makes the page read as closed.
"""

