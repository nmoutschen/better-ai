def require(condition, message):
    if not condition:
        raise ValueError(message)


def lines_of(text: str, jsonl: bool) -> list:
    """The lines of a JSONL file, split on newlines only, without the empty piece after the last; a JSON file is one."""
    if not jsonl:
        return [text]
    pieces = [piece.removesuffix("\r") for piece in text.split("\n")]
    return pieces[:-1] if pieces and pieces[-1] == "" else pieces


MAX_DEPTH = 50  # no record of these files nests deeper than a design.json step


def parse(piece: str):
    """One JSON value as the page can show it: no NaN or Infinity (the browser cannot read them), and nothing nested
    so deep that Python gives up."""

    def refuse(word):
        raise ValueError(f"{word} is not a JSON value")

    def finite(word):
        value = float(word)
        if value in (float("inf"), float("-inf")):
            raise ValueError(f"{word} is too large")
        return value

    try:
        value = json.loads(piece, parse_constant=refuse, parse_float=finite)
    except RecursionError:
        raise ValueError("nested too deeply") from None
    pending = [(value, 1)]
    while pending:  # no recursion: a line may be as deep as it likes
        item, depth = pending.pop()
        if isinstance(item, (dict, list)):
            if depth > MAX_DEPTH:
                raise ValueError(f"nested more than {MAX_DEPTH} levels deep")
            pending.extend((inner, depth + 1) for inner in (item.values() if isinstance(item, dict) else item))
    return value


class Reader:
    """Reads the files of one change folder record by record through schema.py: the records come back, and each
    invalid one goes to `errors` with its file, line, field, reason and, if it parsed, its `by`."""

    def __init__(self, folder: Path):
        self.folder, self.errors, self.cache = folder, [], {}
        self.docs = schema.load_schemas(SCHEMAS)

    def error(self, name, line, field, message, by=None):
        entry = {"file": name, "line": line, "field": field, "message": message}
        self.errors.append({**entry, "by": schema.plain(by)} if isinstance(by, str) and by else entry)

    def records(self, name: str, keep_invalid: bool = False) -> list:
        """What `_records` reads; whatever else goes wrong with one file, for any reason, is that file's error."""
        try:
            return self._records(name, keep_invalid)
        except Exception as exc:
            self.error(name, 1, "(file)", f"could not be shown: {type(exc).__name__}")
            return []

    def _records(self, name: str, keep_invalid: bool = False) -> list:
        """The records of one file, in line order; none if it does not exist. The file is read once and that text is
        validated and shown, so a write in between is in neither. A record with errors is left out, unless
        `keep_invalid`: then it stays without the fields that failed, and its messages in `_errors`, so the page can
        show what it can of it. A line that is not JSON is never a record."""
        path = self.folder / name
        if not path.is_file():
            return []
        jsonl = path.suffix == ".jsonl"
        try:
            text = schema.read_checked(path, jsonl)
        except (OSError, UnicodeDecodeError) as exc:
            self.error(name, 1, "(file)", f"cannot be read: {exc}")
            return []
        try:
            found = schema.check_text(path, text, self.docs, self.cache)
        except (RecursionError, ValueError, TypeError, KeyError, AttributeError, OverflowError) as exc:
            self.error(name, 1, "(file)", f"cannot be checked: {exc}")
            return []
        flagged = {problem.line for problem in found}
        parsed = {}
        for number, piece in enumerate(lines_of(text, jsonl), 1):
            try:
                value = parse(piece)
            except ValueError as exc:
                if number not in flagged:  # valid for the schema, but not for the page
                    self.error(name, number, "(record)", f"not valid JSON: {exc}")
                continue
            parsed[number] = value if isinstance(value, dict) else None
        by_line: dict = {}
        for problem in found:
            record = parsed.get(problem.line)
            self.error(name, problem.line, problem.field, problem.message, record.get("by") if record else None)
            by_line.setdefault(problem.line, []).append(problem)
        kept = []
        for number, record in parsed.items():
            if record is None or (number in by_line and not keep_invalid):
                continue
            if number in by_line:
                record = schema.strip_invalid(record, by_line[number])
                if not isinstance(record.get("id"), str) or not record["id"]:
                    record["id"] = f"(line {number})"
            kept.append(record)
        return kept


def source_file(folder, path):
    """Serve only explicitly linked files, scoped to the change folder's repository."""
    root = next((p for p in (folder, *folder.parents) if (p / ".git").exists()), folder)
    name = Path(path)
    require(
        not name.is_absolute() and not set(name.parts).intersection({"..", ".git"}), f"invalid source path {path!r}"
    )
    target = (root / name).resolve()
    require(target.is_relative_to(root) and target.is_file(), f"missing or out-of-scope source {path!r}")
    return target


def blank(folder: Path, errors: list) -> dict:
    return {
        "errors": errors,
        "architect": {},
        "design": None,
        "parts": {},
        "hashes": {},
        "requirements": [],
        "perspectives": [],
        "findings": [],
        "reviews": [],
        "decisions": [],
        "spec": [],
        "sources": {},
        "name": folder.name,
    }


def read_design(reader: Reader):
    """The design as far as it is usable, with its parts and their fingerprints; no design if it cannot be drawn."""
    records = reader.records("design.json", keep_invalid=True)
    if not (reader.folder / "design.json").is_file():
        reader.error("design.json", 1, "(file)", "missing file")
    design = records[0] if records else None
    if design is None:
        return None, {}, {}
    usable = diagram.without_nulls({"containers": design.get("containers"), "flows": design.get("flows") or []})
    if not isinstance(usable.get("containers"), dict):
        return None, {}, {}
    try:
        parts, hashes = diagram_parts(usable)
        return usable, parts, hashes
    except (AttributeError, IndexError, KeyError, TypeError, ValueError) as exc:
        reader.error("design.json", 1, "(diagram)", str(exc))
        return None, {}, {}


def read_folder(folder: Path) -> dict:
    """Read and validate the folder's files, record by record: the records, the diagram's parts, and `errors`."""
    folder = folder.resolve()
    try:
        reader = Reader(folder)
    except schema.SchemaError as exc:
        return blank(folder, [{"file": "schemas", "line": 1, "field": "(schemas)", "message": str(exc)}])
    meta = reader.records("architect.json", keep_invalid=True)
    if not (folder / "architect.json").is_file():
        reader.error("architect.json", 1, "(file)", "missing file")
    architect = meta[0] if meta else {}
    design, parts, hashes = read_design(reader)
    data = blank(folder, reader.errors)
    data.update(architect=architect, design=design, parts=parts, hashes=hashes)
    for name in FILES[2:]:
        data[Path(name).stem] = reader.records(name, keep_invalid=True)
    request = architect.get("request") if isinstance(architect.get("request"), dict) else {}
    if isinstance(request.get("text"), str):
        data["sources"]["request"] = request["text"]
    for number, record in enumerate(data["requirements"], 1):
        source = record.get("source")
        if isinstance(source, dict) and source.get("type") == "file" and not record.get("_errors"):
            try:  # schema.py has checked that it exists; it may be gone since
                data["sources"][source["file"]] = source_file(folder, source["file"])
            except (OSError, ValueError) as exc:
                reader.error("requirements.jsonl", number, "source.file", str(exc), record.get("by"))
    for name in CHECKED_ONLY:
        reader.records(name)
    return data


def diagram_parts(design):
    """Index the same boxes, arrows and steps across both versions for links and comments."""
    parts, hashes = {}, {}

    def add(key, item, part):
        require(key not in parts, f"duplicate diagram part {key!r}")
        parts[key] = {**part, "key": key}
        hashes[key] = hashlib.sha256(json.dumps(item, sort_keys=True).encode()).hexdigest()

    def ids(view, kind, ident):
        return [diagram.part_id(f"{view}-{state}", kind, ident) for state in diagram.STATES]

    nodes = {node["id"]: node for node in design["containers"]["nodes"]}
    for ident, node in nodes.items():
        add(
            f"box:{ident}",
            node,
            {
                "label": node["label"],
                "kind": "box",
                "ids": ids("c", "box", ident),
                "view": "containers",
                "icon": diagram.glyph(node["kind"]),
            },
        )
    for edge in design["containers"].get("edges", []):
        ident = edge["id"]
        route = f"{nodes[edge['from']]['label']} to {nodes[edge['to']]['label']}"
        add(
            f"edge:{ident}",
            edge,
            {
                "label": f"{route}: {edge.get('label', '')}",
                "route": route,
                "kind": "edge",
                "view": "containers",
                "ids": ids("c", "edge", ident),
            },
        )
    for i, flow in enumerate(design["flows"], 1):
        view = f"flow{i}"  # the drawing's own name for the flow; no stored key uses it
        participants = {p["id"]: nodes[p["box"]]["label"] for p in flow["participants"]}
        for participant in flow["participants"]:
            parts[f"box:{participant['box']}"]["ids"].extend(ids(view, "box", participant["id"]))
        for step, number in zip(flow["steps"], diagram.step_numbers(flow), strict=True):
            ident = step["id"]
            route = f"{participants[step['from']]} to {participants[step['to']]}"
            description = f"{step.get('label', '')} (Flows, step {number})"
            add(
                f"step:{flow['id']}/{ident}",
                step,
                {
                    "label": f"{route}: {description}",
                    "description": description,
                    "kind": "step",
                    "ids": ids(view, "step", ident),
                    "view": "flows",
                    "mark": f"{view}:step:{ident}",
                },
            )
    return parts, hashes


def changed_parts(hashes, review):
    previous = review["hashes"] if review else {}
    return [key for key in dict.fromkeys((*hashes, *previous)) if hashes.get(key) != previous.get(key)]


def render_diagrams(design, marks):
    try:
        layout = diagram.layout({**design, "findings": marks})
        containers = {s: diagram.svg_containers(layout, s) for s in diagram.STATES}
        flows = [
            {
                "name": flow["name"],
                "new": flow.get("in") == ["after"],
                "versions": {
                    s: diagram.svg_flow(flow, s, layout, f"flow{i}") if diagram.visible(flow, s) else ""
                    for s in diagram.STATES
                },
            }
            for i, flow in enumerate(design["flows"], 1)
        ]
    except (AttributeError, IndexError, KeyError, TypeError, ValueError) as exc:
        raise ValueError(f"design.json:1: {exc}") from exc
    return containers, flows


def text_of(record, key, default=""):
    value = record.get(key)
    return value if isinstance(value, str) else default


def list_of(record, key):
    value = record.get(key)
    return value if isinstance(value, list) else []


def shown(record, **defaults):
    """A record as the page draws it: the fields it has, and a harmless default for each one it lost to an error."""
    record = {k: v for k, v in record.items() if v is not None}  # an optional field that is null is absent
    return {**{k: v for k, v in defaults.items() if k not in record}, **record}


def model(data):
    """What the page shows: the records, the diagrams with the findings marked, what changed since the last review and
    which perspectives must run again, and `errors`. It draws what it is given: a record that is not valid arrives
    without the fields that failed."""
    errors = list(data["errors"])
    design, parts = data["design"], data["parts"]
    reviews = [shown(r, perspectives=[], changed=[], hashes={}, labels={}) for r in data["reviews"]]
    review = reviews[-1] if reviews else None
    changes = dict.fromkeys(changed_parts(data["hashes"], review) if design else [])
    known = set(parts)
    for recorded in reviews:
        known.update(recorded["hashes"])
    marks, findings_by_perspective = {}, {}
    findings = [shown(f, perspective="", parts=[], text="", confirmed=False, status="open") for f in data["findings"]]
    for finding in findings:
        keys = {part for group in finding["parts"] for part in group.split("+") if part in known}
        findings_by_perspective.setdefault(finding["perspective"], set()).update(keys)
        if review:
            for key in sorted(keys.intersection(parts)):
                target = parts[key].get("mark", key.removeprefix("box:"))
                marks.setdefault(target, []).append([finding["id"], finding["text"], finding["perspective"]])
        finding["handled_by"] = finding.get("handled_by") if finding["status"] == "handled" else None

    with_findings = set().union(*findings_by_perspective.values())
    last_reviews, labels = {}, {}
    for recorded in reviews:
        labels.update(recorded["labels"])
        for ident in recorded["perspectives"]:
            last_reviews[ident] = recorded
    labels.update((key, part["label"]) for key, part in parts.items())

    perspectives = [
        shown(p, name=p["id"], applies=False, why="", **{"from": {"type": "missing"}}) for p in data["perspectives"]
    ]
    rerun = []
    for perspective in perspectives:
        if perspective["applies"] is not True or not design:
            continue
        ident = perspective["id"]
        last = last_reviews.get(ident)
        own_findings = findings_by_perspective.get(ident, set())
        affected = (
            [key for key in changed_parts(data["hashes"], last) if key in own_findings or key not in with_findings]
            if last
            else []
        )
        if last is None or affected:
            rerun.append(ident)
            changes.update(dict.fromkeys(affected))
    containers, flows = {state: "" for state in diagram.STATES}, []
    if design:
        try:
            containers, flows = render_diagrams(design, marks)
        except ValueError as exc:
            errors.append({"file": "design.json", "line": 1, "field": "(diagram)", "message": str(exc)})
    meta = data["architect"]
    requirements = [shown(r, kind="", text="", source={"type": "missing"}) for r in data["requirements"]]
    return {
        "errors": errors,
        "title": text_of(meta, "title", data["name"]),
        "summary": text_of(meta, "summary"),
        "scope": text_of(meta, "scope"),
        "accepted": [t for t in list_of(meta, "accepted") if t in TABS],
        "requirements": [{**req, "wording": hashlib.sha256(req["text"].encode()).hexdigest()} for req in requirements],
        "perspectives": perspectives,
        "findings": findings,
        "reviews": reviews,
        "decisions": [shown(d, title="", drivers=[], chosen="", rejected=[], drawback="") for d in data["decisions"]],
        "spec": [shown(r, statement="", source=None, checked_by="") for r in data["spec"]],
        "parts": parts,
        "since": list(changes),
        "removed": [key for key in changes if key not in parts],
        "change_labels": {key: labels.get(key, key) for key in changes},
        "removed_labels": {key: labels.get(key, key) for key in known if key not in parts},
        "rerun": rerun,
        "containers": containers,
        "flows": flows,
    }


def load(folder: Path) -> dict:
    """The page's payload for a folder. It never raises for a bad file: what is wrong is in `errors`."""
    try:
        return model(read_folder(folder))
    except Exception as exc:  # for any reason: the page shows its errors band, not a failure
        message = f"could not be shown: {type(exc).__name__}"
        error = {"file": "(folder)", "line": 1, "field": "(folder)", "message": message}
        return empty_model(folder, error)


def empty_model(folder: Path, error: dict) -> dict:
    """What `model` makes of a folder with nothing readable, written out so that no failure can reach it."""
    return {
        "errors": [error],
        "title": folder.name,
        "summary": "",
        "scope": "",
        "accepted": [],
        "requirements": [],
        "perspectives": [],
        "findings": [],
        "reviews": [],
        "decisions": [],
        "spec": [],
        "parts": {},
        "since": [],
        "removed": [],
        "change_labels": {},
        "removed_labels": {},
        "rerun": [],
        "containers": {state: "" for state in ("before", "after")},
        "flows": [],
    }


def record_review(folder, perspectives):
    require_writable_folder(folder)
    path = folder / "reviews.jsonl"
    existed = path.exists()
    try:
        with path.open("a+", encoding="utf-8") as log:
            fcntl.flock(log, fcntl.LOCK_EX)
            data = read_folder(folder)
            require(not data["errors"], "fix the folder first:\n" + "\n".join(error_lines(data["errors"])))
            applicable = {p["id"] for p in data["perspectives"] if p["applies"]}
            for ident in perspectives:
                require(
                    ident in applicable, f"unknown or inapplicable perspective {ident!r}: use the id of a perspective"
                )
            previous = data["reviews"][-1] if data["reviews"] else None
            record = {
                "type": "review",
                "at": page.now(),
                "by": "architect",
                "perspectives": list(dict.fromkeys(perspectives)),
                "changed": changed_parts(data["hashes"], previous),
                "hashes": data["hashes"],
                "labels": {key: data["parts"][key]["label"] for key in data["hashes"]},
            }
            log.seek(0)
            content = log.read()
            separator = "\n" if content and not content.endswith("\n") else ""
            log.write(separator + json.dumps(record) + "\n")
    except ValueError:
        if not existed:
            path.unlink(missing_ok=True)  # opening it made an empty file; a refused review leaves none
        raise


def error_lines(errors):
    return [f"{e['file']}:{e['line']}: {e['field']}: {e['message']}" for e in errors]


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def source_words(source):
    """A spec source in words, for the table of specs.md."""
    if not isinstance(source, dict):
        return ""
    kind = source.get("type")
    if kind == "design":
        return f"design: {source.get('section', '')}"
    if kind == "request":
        return f'request: "{source.get("sentence", "")}"'
    return f"{kind} {source.get(kind, '')}"


def specs_md(records, meta):
    """The spec for a repo with no spec format or tool, written from spec.jsonl and marked as generated."""
    out = [GENERATED, "", f"# Spec: {meta.get('title', '')}", ""]
    if meta.get("summary"):
        out += [meta["summary"], ""]
    out += ["| ID | Requirement | Source | Checked by |", "|---|---|---|---|"]
    for record in records:
        if record.get("type") == "spec":
            statement, checked = cell(record.get("statement", "")), cell(record.get("checked_by", ""))
            out.append(
                f"| {record.get('id', '')} | {statement} | {cell(source_words(record.get('source')))} | {checked} |"
            )
    gaps = [r for r in records if r.get("type") == "gap"]
    if gaps:
        out += ["", "## Gaps", ""]
        for gap in gaps:
            if gap.get("status") == "assumed":
                how = f"assumed: {gap.get('choice')}"
            else:
                how = f"{gap.get('status')} ({gap.get('decision')})"
            out.append(
                f"- {gap.get('id')}: {gap.get('text')} {how}. If wrong, the user would see: {gap.get('if_wrong')}"
            )
    unlinked = [r for r in records if r.get("type") == "unlinked"]
    if unlinked:
        out += ["", "## Design items with no requirement", ""]
        out += [f"- {item.get('item')}: {item.get('why')}" for item in unlinked]
    return "\n".join(out) + "\n"


def write_specs(folder, out):
    data = read_folder(folder)
    mine = [e for e in data["errors"] if e["file"] in ("spec.jsonl", "architect.json")]
    require(not mine, "fix spec.jsonl first:\n" + "\n".join(error_lines(mine)))
    require(any(r.get("type") == "spec" for r in data["spec"]), "spec.jsonl has no records: write the spec first")
    require(
        not out.exists() or out.read_text(encoding="utf-8").startswith(GENERATED),
        f"{out} exists and was not generated by this command: it keeps its own text",
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(specs_md(data["spec"], data["architect"]), encoding="utf-8")


def conversation(folder: Path) -> page.Conversation:
    return page.Conversation(
        folder,
        "conversation.jsonl",
        ".conversation-seen",
        ".server",
        ITEMS,
        "architect",
        "architect.py serve CHANGE --no-browser",
        schemas=SCHEMAS,
        events="architect-events.schema.json",
    )


def require_writable_folder(folder):
    require(
        not folder.resolve().is_relative_to(HERE.parents[1]),
        "serve writes conversation files; use a copy of the change folder outside skills/",
    )


def fingerprint(paths):
    rev = hashlib.sha256()
    for path in paths:
        try:
            rev.update(path.read_bytes())
        except OSError:
            rev.update(b"-")
    return rev.hexdigest()


def serve(folder: Path, port: int, open_browser: bool) -> None:
    require_writable_folder(folder)
    conv = conversation(folder)

    class Handler(page.Handler):
        conversation = conv
        methods = METHODS

        def do_GET(self):
            if self.conversation_get():
                return
            url = urlsplit(self.path)
            try:
                if url.path in ASSETS:
                    name, kind = ASSETS[url.path]
                    self.send(200, (HERE / name).read_bytes(), kind + "; charset=utf-8")
                elif url.path == "/design.json":
                    self.send_json(load(folder))
                elif url.path == "/rev":
                    files = [*(folder / name for name in FILES), *(HERE / name for name, _ in ASSETS.values())]
                    self.send(200, fingerprint(files).encode(), "text/plain")
                elif url.path == "/source":
                    args = parse_qs(url.query)
                    path = args.get("file", [""])[0]
                    source = read_folder(folder)["sources"].get(path)
                    if source is None:
                        self.send_error(404)
                    else:
                        text = source if isinstance(source, str) else source.read_text(encoding="utf-8")
                        lines = text.splitlines()
                        line = args.get("line", [""])[0]
                        if line.isdecimal() and 0 < int(line) <= len(lines):
                            n = int(line)
                            lines = [f"{i + 1:>5}  {lines[i]}" for i in range(max(0, n - 4), min(len(lines), n + 3))]
                        self.send(200, "\n".join(lines).encode(), "text/plain; charset=utf-8")
                else:
                    self.send_error(404)
            except (OSError, ValueError, KeyError, TypeError) as exc:
                self.send(400, str(exc).encode(), "text/plain; charset=utf-8")

    with http.server.ThreadingHTTPServer(("127.0.0.1", port), Handler) as server:
        url = f"http://127.0.0.1:{server.server_address[1]}/"
        conv.address.write_text(url, encoding="utf-8")
        print(f"Serving {folder} at {url}. Each action is printed as one JSON line.", flush=True)
        try:
            if open_browser:
                webbrowser.open(url)
            page.stop_like_ctrl_c()
            server.serve_forever()
        except KeyboardInterrupt:
            pass
        finally:
            conv.address.unlink(missing_ok=True)


@schema.never_raise(
    "change folder", {**page.VERBS, "serve": "served", "review": "written", "specs": "written", "": "checked"}
)
def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    commands = {
        name: sub.add_parser(name, help=help_text)
        for name, help_text in (
            ("serve", "serve the live design"),
            ("check", "validate the change folder; print each error and exit 1 if there is one"),
            ("review", "record the reviewed diagram fingerprints"),
            ("specs", "write specs.md from spec.jsonl, marked as generated"),
            ("wait", "wait for new user actions"),
            ("reply", "reply in the conversation"),
            ("status", "mark an item with its current state"),
            ("pending", "list unfinished items"),
        )
    }
    for command in commands.values():
        command.add_argument("change", type=Path)
    commands["serve"].add_argument("--port", type=int, default=0)
    commands["serve"].add_argument("--no-browser", action="store_true")
    commands["review"].add_argument("--perspectives", nargs="+", required=True, metavar="ID")
    commands["specs"].add_argument("--out", type=Path, required=True, help="the specs.md to write")
    commands["wait"].add_argument("--timeout", type=float, default=600)
    commands["reply"].add_argument("text")
    commands["reply"].add_argument("--to", metavar="ID")
    commands["status"].add_argument("state", choices=page.STATES)
    commands["status"].add_argument("ids", nargs="+")
    commands["status"].add_argument("--text", help="the user's words, for accepted")
    args = parser.parse_args(argv)
    folder = args.change.expanduser().resolve()
    if not folder.is_dir():
        parser.error(f"{folder} is not a directory")
    conv = conversation(folder)
    try:
        if args.command in ("wait", "reply", "status"):
            require_writable_folder(folder)
        if args.command == "check":
            errors = load(folder)["errors"]
            for line in error_lines(errors):
                print(line)
            if errors:
                return 1
            print(f"Valid change folder: {folder}")
        elif args.command == "review":
            record_review(folder, args.perspectives)
        elif args.command == "specs":
            write_specs(folder, args.out.expanduser().resolve())
        elif args.command == "serve":
            serve(folder, args.port, not args.no_browser)
        elif args.command == "wait":
            return conv.wait(args.timeout)
        elif args.command == "reply":
            conv.reply(args.text, args.to)
        elif args.command == "status":
            conv.set_status(args.state, args.ids, args.text)
        else:
            conv.pending()
    except ValueError as exc:  # what the user can fix; any other failure is the wrapper's one line
        parser.error(str(exc))
    return 0


if __name__ == "__main__":
    sys.exit(main())
